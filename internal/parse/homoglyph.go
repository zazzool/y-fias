package parse

import "strings"

// Свёртка визуальных двойников.
//
// Диспетчер печатает быстро и не всегда замечает раскладку. В проде это видно:
// среди 2 033 написаний номера дома есть «З2к1», где первый символ —
// кириллическая «З», а не цифра 3.
//
// ВАЖНО: свёртка нужна, чтобы ПОНЯТЬ ввод, а не чтобы его исправить. Функция
// возвращает признак того, что двойники были, и вызывающий код обязан
// выставить FlagHomoglyph. Сам Raw остаётся неизменным (инвариант 1).

// latinToCyrillic — латинские буквы, визуально неотличимые от кириллических.
// Только те, где начертание совпадает: «c» и «с», но не «g» и «г».
// Регистр приводится до свёртки, поэтому достаточно строчных.
var latinToCyrillic = map[rune]rune{
	'a': 'а',
	'c': 'с',
	'e': 'е',
	'o': 'о',
	'p': 'р',
	'x': 'х',
	'y': 'у',
}

// digitLookalikes — кириллические буквы на месте цифр. Применяются ТОЛЬКО в
// числовом окружении: «З2к1» -> «32к1», но «Зорге» трогать нельзя.
var digitLookalikes = map[rune]rune{
	'з': '3',
	'о': '0',
}

// keyboardLayout — раскладка QWERTY -> ЙЦУКЕН для случая, когда переключить
// забыли целиком. «7r7» -> «7к7».
var keyboardLayout = map[rune]rune{
	'q': 'й', 'w': 'ц', 'e': 'у', 'r': 'к', 't': 'е', 'y': 'н', 'u': 'г',
	'i': 'ш', 'o': 'щ', 'p': 'з', '[': 'х', ']': 'ъ',
	'a': 'ф', 's': 'ы', 'd': 'в', 'f': 'а', 'g': 'п', 'h': 'р', 'j': 'о',
	'k': 'л', 'l': 'д', ';': 'ж', '\'': 'э',
	'z': 'я', 'x': 'ч', 'c': 'с', 'v': 'м', 'b': 'и', 'n': 'т', 'm': 'ь',
	',': 'б', '.': 'ю',
}

// foldHomoglyphs приводит строку к нижнему регистру и сворачивает визуальных
// двойников к кириллице и цифрам. Второе значение — были ли замены.
//
// Регистр приводится ЗДЕСЬ, а не в вызывающем коде, и это существенно.
// Раньше свёртка шла до приведения регистра, и прописные буквы вне диапазона
// A-Z (например турецкая «İ») её проскакивали, а их строчные формы — уже нет.
// Из-за этого «0İ» разбиралось в «0i», а повторный разбор давал «0ш»:
// каноническая форма переставала быть неподвижной точкой. Нашёл фаззинг.
func foldHomoglyphs(s string) (string, bool) {
	if s == "" {
		return "", false
	}

	runes := []rune(strings.ToLower(s))
	changed := false

	// Первый проход: латиница, похожая на кириллицу.
	for i, r := range runes {
		if c, ok := latinToCyrillic[r]; ok {
			runes[i] = c
			changed = true
		}
	}

	// Второй проход: латиница, НЕ похожая на кириллицу, но стоящая среди цифр.
	//
	// «7r7» — это «7к7», набранное в латинской раскладке: визуально «r» и «к»
	// не похожи, поэтому первый проход их не ловит. В номере дома латинской
	// букве взяться неоткуда, так что перевод по раскладке здесь обоснован.
	// В названии улицы такое правило было бы опасно и там не применяется.
	for i, r := range runes {
		if !isLatinLetter(r) {
			continue
		}
		if c, ok := keyboardLayout[toLowerASCII(r)]; ok {
			runes[i] = c
			changed = true
		}
	}

	// Третий проход: буквы на месте цифр.
	//
	// Условие строгое — заменяем, только если СЛЕДУЮЩИЙ символ цифра:
	//
	//	«З2к1» -> «32к1»   З перед цифрой: это тройка
	//	«1О2»  -> «102»    О между цифрами: это ноль
	//	«2о»   -> «2о»     о ПОСЛЕ цифр: это литера, не ноль
	//
	// Ранее условием было «цифра слева ИЛИ справа», и «2о» превращалось в
	// «20» — то есть номер дома менялся молча. Нашёл фаззинг: разбор
	// канонической формы «2о» давал «20», и форма переставала быть
	// неподвижной точкой. Случай не теоретический: литеры «о», «О», «З»
	// в номерах домов встречаются.
	for i, r := range runes {
		d, ok := digitLookalikes[r]
		if !ok {
			continue
		}
		if i+1 < len(runes) && isDigit(runes[i+1]) {
			runes[i] = d
			changed = true
		}
	}

	return string(runes), changed
}

// IsLikelyWrongLayout сообщает, что строка похожа на набранную в латинской
// раскладке. Перенесено из server/utils/keyboardLayout.ts.
//
// Автозамены нет и не будет: функция только даёт основание ПРЕДЛОЖИТЬ
// исправление (инвариант 1).
func IsLikelyWrongLayout(s string) bool {
	var latin, cyrillic int
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z':
			latin++
		case r >= 'а' && r <= 'я', r >= 'А' && r <= 'Я', r == 'ё', r == 'Ё':
			cyrillic++
		}
	}
	return latin > 0 && cyrillic == 0
}

// LatinToCyrillicLayout переводит строку из латинской раскладки в кириллицу.
// Результат — ПРЕДЛОЖЕНИЕ пользователю, не подстановка.
func LatinToCyrillicLayout(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		lower := r
		upper := false
		if r >= 'A' && r <= 'Z' {
			lower = r + ('a' - 'A')
			upper = true
		}
		c, ok := keyboardLayout[lower]
		if !ok {
			b.WriteRune(r)
			continue
		}
		if upper {
			c = []rune(strings.ToUpper(string(c)))[0]
		}
		b.WriteRune(c)
	}
	return b.String()
}

func isLatinLetter(r rune) bool {
	return (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z')
}

func toLowerASCII(r rune) rune {
	if r >= 'A' && r <= 'Z' {
		return r + ('a' - 'A')
	}
	return r
}
