// Команда gen порождает sql/normalize.sql из пакета normalize.
//
// Смысл: у правила нормализации должен быть ОДИН источник (инвариант 5).
// Список типов улиц объявлен в Go, а SQL собирается из него, поэтому
// разойтись они не могут физически. CI выполняет `go generate` и падает,
// если результат отличается от закоммиченного.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/zazzool/y-fias/internal/normalize"
)

func main() {
	out := flag.String("out", "", "путь к выходному .sql")
	flag.Parse()

	if *out == "" {
		fmt.Fprintln(os.Stderr, "не указан -out")
		os.Exit(1)
	}

	if err := os.WriteFile(*out, render(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "запись %s: %v\n", *out, err)
		os.Exit(1)
	}
}

func render() []byte {
	var b bytes.Buffer

	b.WriteString(`-- CODE GENERATED BY internal/normalize/gen. DO NOT EDIT.
--
-- Источник правды — пакет internal/normalize. Правки вносятся ТАМ, затем
-- выполняется `)
	b.WriteString("`make generate`")
	b.WriteString(`.
--
-- Зачем генерация. До Y-FIAS список типов улиц существовал в трёх копиях:
-- SQL-функция street_key() (миграция 0029), normalizeStreetKey() в
-- orgMatcher.ts и STREET_TYPE_RE в addressService.ts. Копии разошлись, и это
-- порождало дубликаты адресов — 64 группы из 81 в проде. Сгенерированный SQL
-- разойтись с Go не может.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ── search_norm: текст для триграммного поиска ──────────────────
--
-- ё→е обязательно: в базе встречаются оба написания одной улицы, и триграммы
-- у них не пересекаются на месте буквы.
--
-- Дефис → пробел: «3-я Парковая» должна находиться и по «парковая».
--
-- «й» НЕ сводится к «и»: это разные буквы. Опечатки такого рода закрывает
-- триграммное сходство, а не нормализация. (Копия в orgMatcher.ts это
-- правило нарушала — см. testdata/reference/README.md §1.4.)
--
-- ОТЛИЧИЕ ОТ ЛЕГАСИ: добавлен btrim. Функция из миграции 0029 не обрезала
-- края, и « Заповедная улица» давала ключ с ведущим пробелом — таких записей
-- в проде 32 из 1265. Расхождение поймал контрактный тест Go<->SQL.
-- При выкладке на прод требуется REINDEX индексов по search_norm.
CREATE OR REPLACE FUNCTION search_norm(t text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT btrim(regexp_replace(
             regexp_replace(
               translate(lower(COALESCE(t, '')), 'ё-–—', 'е   '),
               '[^a-zа-я0-9 ]', ' ', 'g'),
             '\s+', ' ', 'g'))
$$;

-- ── street_key: улица без типа и без учёта порядка слов ─────────
--
-- «улица Саляма Адиля» = «Саляма Адиля ул.» = «саляма адиля».
-- Слова сортируются — именно это делает ключ независимым от порядка.
--
`)

	b.WriteString(renderPostNorm())

	tokens := normalize.StreetTypeTokens()
	fmt.Fprintf(&b, "-- Токенов-типов: %d. Список порождён из normalize.streetTypes.\n", len(tokens))
	b.WriteString(`CREATE OR REPLACE FUNCTION street_key(t text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT COALESCE(NULLIF(
        (SELECT string_agg(w, ' ' ORDER BY w)
         FROM unnest(string_to_array(street_post_norm(t), ' ')) AS w
         WHERE w <> ''
           AND w NOT IN (
`)
	b.WriteString(sqlTokenList(tokens, "               "))
	b.WriteString(`           )), ''),
        -- Улица, целиком состоящая из типа («Линия», «Аллея» как название),
        -- не должна давать пустой ключ — иначе все такие сольются в один.
        search_norm(t))
$$;

-- ── house_num: ведущее число дома ───────────────────────────────
--
-- ТОЛЬКО предфильтр кандидатов. Тождество дома определяется полной
-- канонической формой: «7к7» ≠ «7к1» ≠ «7». Подмена этого правила стоила
-- жалобы и разбора (§8.2 инвентаризации).
CREATE OR REPLACE FUNCTION house_num(h text) RETURNS integer
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT NULLIF((regexp_match(COALESCE(h, ''), '^\s*(\d+)'))[1], '')::integer
$$;

-- ── Контроль ────────────────────────────────────────────────────
-- Ожидается: 'адиля саляма' в обоих ключах, 'е' вместо 'ё', 10 в доме.
--   SELECT street_key('улица Саляма Адиля')  AS key_1,
--          street_key('Саляма Адиля ул.')    AS key_2,
--          search_norm('Хорошёвское шоссе')  AS norm,
--          house_num('10с4кссК')             AS num;
`)

	return b.Bytes()
}

// renderPostNorm собирает street_post_norm() — цепочку regexp_replace,
// повторяющую normalize.postNormalize.
//
// Каждое правило применяется ДВАЖДЫ, как и в Go: соседние совпадения делят
// пробел-разделитель, поэтому за один проход находятся только совпадения
// через одно.
func renderPostNorm() string {
	var b strings.Builder

	b.WriteString(`-- ── street_post_norm: сборка распавшихся сокращений ────────────
--
-- search_norm() превращает дефис в пробел, и это верно для двойных названий
-- («Римский-Корсаков» находится по «корсаков»). Но порядковые числительные и
-- сокращения при этом распадаются:
--
--   «3-я Парковая»   ->  «3 я парковая»
--   «3я Парковая»    ->  «3я парковая»
--   «2- й Парковая»  ->  «2 й парковая»
--
-- Три написания одной улицы — три ключа и до трёх дубликатов. В эталонных
-- ключах прода обрывки «я» и «й» встречаются 210 раз.
--
-- Строка обрамляется пробелами, поэтому границы слов задаются явно и первое
-- со последним словом обрабатываются наравне с остальными.
CREATE OR REPLACE FUNCTION street_post_norm(t text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
    SELECT btrim(
`)

	// Собираем изнутри наружу: во вложенных вызовах первым выполняется
	// ВНУТРЕННИЙ, а правила должны применяться в порядке объявления — как в
	// normalize.postNormalize. Поэтому rules[0] оказывается самым внутренним.
	expr := "' ' || search_norm(t) || ' '"
	for _, r := range normalize.PostNormRules() {
		for pass := 1; pass <= 2; pass++ {
			expr = fmt.Sprintf("regexp_replace(  -- %s, проход %d\n%s,\n%s, %s, 'g')",
				r.Name, pass,
				indentLines(expr, "  "),
				sqlQuote(r.Pattern), sqlQuote(r.Replace))
		}
	}

	b.WriteString(indentLines(expr, "        "))
	b.WriteString("\n    )\n$$;\n\n")
	return b.String()
}

func indentLines(s, pad string) string {
	lines := strings.Split(s, "\n")
	for i := range lines {
		lines[i] = pad + lines[i]
	}
	return strings.Join(lines, "\n")
}

func sqlQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// sqlTokenList печатает токены по несколько в строке, чтобы результат читался
// человеком в code review.
func sqlTokenList(tokens []string, indent string) string {
	const perLine = 6

	var b strings.Builder
	for i := 0; i < len(tokens); i += perLine {
		end := min(i+perLine, len(tokens))

		quoted := make([]string, 0, perLine)
		for _, t := range tokens[i:end] {
			quoted = append(quoted, "'"+strings.ReplaceAll(t, "'", "''")+"'")
		}

		b.WriteString(indent)
		b.WriteString(strings.Join(quoted, ", "))
		if end < len(tokens) {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	return b.String()
}
