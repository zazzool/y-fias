package normalize

import (
	"regexp"
	"strings"
)

// postNormRule — замена, применяемая к УЖЕ нормализованной строке
// (нижний регистр, одиночные пробелы, только буквы и цифры).
//
// Почему после SearchNorm, а не до. SearchNorm превращает дефис в пробел, и
// для двойных названий это верно («Римский-Корсаков» находится по «корсаков»).
// Но у порядковых числительных и сокращений дефис нёс смысл, и после его
// потери строка распадается:
//
//	«3-я Парковая»   ->  «3 я парковая»
//	«3я Парковая»    ->  «3я парковая»
//	«2- й Парковая»  ->  «2 й парковая»
//
// Три написания одной улицы — три ключа и до трёх дубликатов. В эталонных
// ключах прода обрывки «я» и «й» встречаются 210 раз.
//
// Работая ПОСЛЕ нормализации, правила видят единый вид строки и собирают
// распавшееся обратно, независимо от того, как оно распалось.
//
// Границы слов задаются явными пробелами, а не `\b`. Это принципиально: в Go
// `\b` работает только с ASCII, и ровно на этом сломалась legacy-функция
// normalizeStreetForCompare (testdata/reference/README.md §1.2). Строка перед
// применением обрамляется пробелами, поэтому первое и последнее слово
// обрабатываются наравне с остальными.
type postNormRule struct {
	Name    string
	Pattern string // с явными пробелами-границами
	Replace string // SQL-нотация обратных ссылок: \1, \2
}

var postNormRules = []postNormRule{
	{
		// «3 я» -> «3я». Суффикс СОХРАНЯЕТСЯ, а не отбрасывается.
		//
		// Соблазн убрать его целиком («3-я» -> «3») велик и был проверен на
		// реальных данных: он склеивает разные улицы. «2-й проезд Марьиной
		// Рощи» и «2-я улица Марьиной Рощи» существуют оба, а поскольку тип
		// улицы из ключа выбрасывается, единственное, что их различает, — род
		// суффикса. Отбросив его, мы отправили бы бригаду не туда.
		Name:    "порядковые числительные: «3 я» -> «3я»",
		Pattern: ` ([0-9]+) (я|й|е|ое|ая|ый|ой|го) `,
		Replace: ` \1\2 `,
	},
	{Name: "проспект: «пр кт»", Pattern: ` пр (кт|т) `, Replace: ` проспект `},
	{Name: "бульвар: «б р»", Pattern: ` б р `, Replace: ` бульвар `},
	{Name: "проезд: «пр д»", Pattern: ` пр д `, Replace: ` проезд `},
	{Name: "микрорайон: «мк р», «м он»", Pattern: ` (?:мк р|м он|м н) `, Replace: ` микрорайон `},
	{Name: "квартал: «кв л»", Pattern: ` кв л `, Replace: ` квартал `},
	{Name: "набережная: «наб я»", Pattern: ` наб я `, Replace: ` набережная `},
	{Name: "район: «р он», «р н»", Pattern: ` (?:р он|р н) `, Replace: ` район `},
}

var compiledPostNorm = func() []*regexp.Regexp {
	out := make([]*regexp.Regexp, len(postNormRules))
	for i, r := range postNormRules {
		out[i] = regexp.MustCompile(r.Pattern)
	}
	return out
}()

// postNormPasses — сколько раз применяется каждое правило.
//
// Двух проходов достаточно и больше не нужно. Соседние совпадения делят
// пробел-разделитель: в « 1 я 2 я » первое совпадение « 1 я » поглощает
// пробел перед «2», поэтому за один проход находятся только совпадения
// через одно. Второй проход добирает остальные.
//
// Число зафиксировано, а не заменено циклом до неподвижной точки, ровно
// потому, что то же самое должен делать сгенерированный SQL: в PostgreSQL
// цикла нет, там будут два вызова regexp_replace. Одинаковое поведение
// важнее теоретической полноты.
const postNormPasses = 2

// postNormalize применяет правила к нормализованной строке.
func postNormalize(norm string) string {
	if norm == "" {
		return ""
	}

	s := " " + norm + " "
	for i, re := range compiledPostNorm {
		repl := goReplace(postNormRules[i].Replace)
		for range postNormPasses {
			s = re.ReplaceAllString(s, repl)
		}
	}
	return strings.TrimSpace(s)
}

// goReplace переводит SQL-нотацию обратных ссылок в Go.
// Одна нотация в объявлении важнее экономии этой функции: правило должно
// читаться одинаково и в Go, и в сгенерированном SQL.
func goReplace(s string) string { return backrefToGo.Replace(s) }

var backrefToGo = strings.NewReplacer(
	`\1`, `${1}`,
	`\2`, `${2}`,
	`\3`, `${3}`,
)

// PostNormRules отдаёт правила генератору SQL.
func PostNormRules() []postNormRule { return postNormRules }
